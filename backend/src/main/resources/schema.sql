CREATE TABLE IF NOT EXISTS channels (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, code VARCHAR(40) NOT NULL UNIQUE,
 merchant_no VARCHAR(80) NOT NULL, opening_date DATE NOT NULL,
 opening_balance BIGINT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, kind VARCHAR(20) NOT NULL,
 channel_id BIGINT NOT NULL REFERENCES channels(id),
 left_source VARCHAR(20) NOT NULL, right_source VARCHAR(20) NOT NULL,
 match_mode VARCHAR(20) NOT NULL, tolerance BIGINT NOT NULL DEFAULT 0,
 settlement_days INT NOT NULL DEFAULT 0, start_date DATE NOT NULL, last_date DATE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, auto_run BOOLEAN NOT NULL DEFAULT FALSE,
 schedule_time VARCHAR(5) NOT NULL DEFAULT '09:00'
);
CREATE TABLE IF NOT EXISTS import_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 channel_id BIGINT NOT NULL REFERENCES channels(id), source VARCHAR(20) NOT NULL,
 business_date DATE NOT NULL, filename VARCHAR(200) NOT NULL, content_hash VARCHAR(64) NOT NULL,
 inserted_count INT NOT NULL, skipped_count INT NOT NULL, actor VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(channel_id, source, business_date, content_hash)
);
CREATE TABLE IF NOT EXISTS source_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL REFERENCES import_batches(id), channel_id BIGINT NOT NULL REFERENCES channels(id),
 source VARCHAR(20) NOT NULL, external_id VARCHAR(100) NOT NULL,
 order_no VARCHAR(100) NOT NULL, business_type VARCHAR(20) NOT NULL,
 amount BIGINT NOT NULL, trade_status VARCHAR(20) NOT NULL, trade_date DATE NOT NULL,
 UNIQUE(channel_id, source, external_id)
);
CREATE INDEX IF NOT EXISTS idx_records_scope ON source_records(channel_id, source, trade_date);
CREATE TABLE IF NOT EXISTS reconciliation_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id), business_date DATE NOT NULL, attempt INT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, stale BOOLEAN NOT NULL DEFAULT FALSE, total_count INT NOT NULL, matched_count INT NOT NULL,
 difference_count INT NOT NULL, left_amount BIGINT NOT NULL, right_amount BIGINT NOT NULL,
 duration_ms BIGINT NOT NULL, rule_snapshot CLOB NOT NULL, actor VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(project_id, business_date, attempt)
);
ALTER TABLE reconciliation_runs ADD COLUMN IF NOT EXISTS stale BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS reconciliation_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id BIGINT NOT NULL REFERENCES reconciliation_runs(id), match_key VARCHAR(250) NOT NULL,
 result VARCHAR(30) NOT NULL, left_amount BIGINT NOT NULL, right_amount BIGINT NOT NULL,
 left_count INT NOT NULL, right_count INT NOT NULL, detail VARCHAR(500) NOT NULL
);
CREATE TABLE IF NOT EXISTS differences (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id BIGINT NOT NULL REFERENCES reconciliation_runs(id), item_id BIGINT NOT NULL REFERENCES reconciliation_items(id),
 status VARCHAR(30) NOT NULL DEFAULT 'OPEN', delta BIGINT NOT NULL, resolved_amount BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS resolution_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 difference_id BIGINT NOT NULL REFERENCES differences(id), amount BIGINT NOT NULL,
 method VARCHAR(40) NOT NULL, note VARCHAR(1000) NOT NULL, evidence VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', requester VARCHAR(80) NOT NULL,
 reviewer VARCHAR(80), review_note VARCHAR(1000), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS vouchers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference_type VARCHAR(30) NOT NULL, reference_id BIGINT NOT NULL,
 debit_account VARCHAR(100) NOT NULL, credit_account VARCHAR(100) NOT NULL,
 amount BIGINT NOT NULL CHECK(amount > 0), note VARCHAR(500) NOT NULL,
 reversal_of BIGINT REFERENCES vouchers(id), actor VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(reference_type, reference_id)
);
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor VARCHAR(80) NOT NULL, action VARCHAR(50) NOT NULL, target VARCHAR(100) NOT NULL,
 detail VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
