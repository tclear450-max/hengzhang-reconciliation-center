test('late source records invalidate old results and the UI reruns the last day',async({page})=>{
  await login(page)
  await page.evaluate(async({day})=>{
    const session=await fetch('/api/session').then(r=>r.json())
    const call=async(path:string,body:unknown)=>{
      const response=await fetch(`/api${path}`,{method:'POST',headers:{'Content-Type':'application/json','X-XSRF-TOKEN':session.csrfToken},body:JSON.stringify(body)})
      const data=await response.json();if(!response.ok)throw new Error(data.message);return data
    }
    const channel=await call('/channels',{name:'晚到账单测试账户',code:'E2E_LATE',merchantNo:'M-LATE',openingDate:day,openingBalance:'0'})
    const project=await call('/projects',{name:'E2E晚到账单核对',kind:'TRANSACTION',channelId:channel.id,leftSource:'PLATFORM',rightSource:'CLEARING',matchMode:'ONE_TO_ONE',tolerance:'0',settlementDays:0,startDate:day,enabled:true,autoRun:false,scheduleTime:'09:00'})
    for(const source of ['PLATFORM','CLEARING']) await call('/imports/json',{channelId:channel.id,source,businessDate:day,rows:[{externalId:`${source}-1`,orderNo:'LATE-1',businessType:'PAYMENT',amount:'1.00',status:'SUCCESS',tradeDate:day}]})
    await call('/runs',{projectId:project.id,businessDate:day,rerun:false})
    await call('/imports/json',{channelId:channel.id,source:'PLATFORM',businessDate:day,rows:[{externalId:'PLATFORM-2',orderNo:'LATE-2',businessType:'PAYMENT',amount:'2.00',status:'SUCCESS',tradeDate:day}]})
  },{day})
  await page.getByRole('button',{name:'刷新数据',exact:true}).click()
  await expect(page.locator('.stale-notice')).toContainText('1 个任务的账单已更新')
  await page.locator('.stale-notice').click()
  const row=page.locator('tbody tr').filter({hasText:'E2E晚到账单核对'})
  await expect(row).toContainText('需重对');await row.getByRole('button',{name:'执行',exact:true}).click()
  const dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('checkbox',{name:'重新核对最后一个对账日（保留旧版本）'})).toBeChecked()
  await expect(dialog.getByLabel('对账日期',{exact:true})).toHaveValue(day)
  await dialog.getByRole('button',{name:'执行对账',exact:true}).click();await expect(dialog).not.toBeVisible()
  await expect(row).not.toContainText('需重对')
  await nav(page,'对账任务');await page.getByRole('textbox',{name:'搜索当前列表'}).fill('E2E晚到账单核对')
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await expect(page.locator('tbody')).toContainText('v2 · 有效')
  await expect(page.locator('tbody')).toContainText('v1 · 已重对')
})
