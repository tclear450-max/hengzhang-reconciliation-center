async function login(page:Page,username='admin') {
  await page.goto('/')
  await page.getByLabel('操作账号').fill(username)
  await page.getByLabel('登录密码').fill('demo123456')
  await page.getByRole('button',{name:'进入工作台'}).click()
  await expect(page.locator('h1')).toContainText('对账总览')
}
async function nav(page:Page,title:string){await page.locator('.sidebar nav').getByRole('button',{name:title,exact:false}).click();await expect(page.locator('h1')).toContainText(title)}
